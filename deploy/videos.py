import tts


def spell(letters):
    """"K, A, T, E" -> what the voice reads: each letter with its exact American pronunciation, short pauses between."""
    out = []
    for tok in [t.strip() for t in letters.split(",")]:
        out.append("double " + tts.letter(tok[-1]) if tok.startswith("double ") else tts.letter(tok))
    return ' <break time="0.5s" /> '.join(out) + "."


